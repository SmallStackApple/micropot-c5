/*
 * Generic Linux 4.19 server brand.
 *
 * Presents a plain, distro-neutral x86_64 Linux 4.19 host: OpenSSH 7.9p1
 * banner, Apache/2.4.38 "It works!" site, vsftpd 3.0.3 and an interactive
 * bash-flavoured root shell over a fake filesystem (linux419_fs.c). The
 * TCP/IP wire personality comes from the stack419 engine parameters; the
 * shell's network answers are generated live by mp_linuxsh from mp_net so
 * the shell story matches ARP/the wire.
 */
#include <stdio.h>
#include <string.h>

#include "mp_brand_linux419.h"
#include "mp_cfg.h"
#include "mp_ftpd_behavior.h"
#include "mp_http_behavior.h"
#include "mp_httpd_behavior.h"
#include "mp_linuxsh.h"
#include "mp_net.h"
#include "mp_ssh_behavior.h"
#include "mp_sshd_behavior.h"
#include "mp_telnet_behavior.h"

/* Embedded page resources (legacy lwIP http fallback; see CMakeLists). */
extern const uint8_t linux_login_html_start[] asm("_binary_linux_login_html_start");
extern const uint8_t linux_fail_html_start[]  asm("_binary_linux_fail_html_start");
extern const uint8_t linux_admin_html_start[] asm("_binary_linux_admin_html_start");

/* Host keys generated once for this honeypot identity (keys/, DER).
 * A real host keeps stable host keys across boots; so do we.
 * PEM sources live alongside; wolfSSH here is built without WOLFSSH_CERTS,
 * so the PEM path is unavailable and the keys are embedded as DER. */
extern const uint8_t ssh_host_rsa_key_start[]   asm("_binary_ssh_host_rsa_key_der_start");
extern const uint8_t ssh_host_rsa_key_end[]     asm("_binary_ssh_host_rsa_key_der_end");
extern const uint8_t ssh_host_ecdsa_key_start[] asm("_binary_ssh_host_ecdsa_key_der_start");
extern const uint8_t ssh_host_ecdsa_key_end[]   asm("_binary_ssh_host_ecdsa_key_der_end");

/* ------------------------------------------------------- weak credentials */

/* /etc/shadow carries exactly one hash per account, so the accepted set
 * must be exactly the shadow's — a second working password for root
 * would contradict what john cracks out of the box's own shadow.
 * Runtime overrides (cred.root/cred.admin via mp_cfg) win over these;
 * the shadow hash is regenerated on every change (same salt). */
static const mp_cred_t s_creds[] = {
    { .user = "root",  .pass = "toor" },
    { .user = "admin", .pass = "admin" },
};

static void on_cred_change(const char *key)
{
    (void)key;
    mp_linux419_shadow_rebuild();
}

static const mp_cfg_key_t s_cred_keys[] = {
    { "cred.root",  MP_CFG_T_STR, { .u.str = "" }, 0, 0, NULL, true, on_cred_change },
    { "cred.admin", MP_CFG_T_STR, { .u.str = "" }, 0, 0, NULL, true, on_cred_change },
};

/* ------------------------------------------------------------- HTTP pages */

/* Apache upstream default index (docs/docroot/index.html): a fresh install
 * with no site deployed yet. Distro-branded pages are avoided on purpose. */
static const char s_index_html[] =
    "<html><body><h1>It works!</h1></body></html>\n";

static const mp_httpd_route_t s_httpd_routes[] = {
    { "/",           "text/html; charset=UTF-8", s_index_html, 0 },
    { "/index.html", "text/html; charset=UTF-8", s_index_html, 0 },
};

static const mp_httpd_behavior_t s_httpd = {
    .server_hdr = "Apache/2.4.38",
    .server_name = "linux",
    .realm = NULL, /* default vhost: no auth, "It works!" + Apache 404s */
    .routes = s_httpd_routes,
    .n_routes = sizeof(s_httpd_routes) / sizeof(s_httpd_routes[0]),
};

/* Legacy lwIP http behaviour (only used if the persona ever runs on the
 * lwIP transport). */
static const mp_http_behavior_t s_http = {
    .server_hdr = "Apache/2.4.38",
    .realm = "Restricted Area",
    .login_html = (const char *)linux_login_html_start,
    .fail_html = (const char *)linux_fail_html_start,
    .admin_html = (const char *)linux_admin_html_start,
    .creds = s_creds,
    .n_creds = sizeof(s_creds) / sizeof(s_creds[0]),
    .routes = NULL,
    .n_routes = 0,
};

/* -------------------------------------------------------------- metadata */

static const mp_brand_meta_t s_meta = {
    .id = "linux_419",
    .vendor = "Linux",
    .model = "4.19",
    .firmware = "#1 SMP",
    .hostname = "linux",
    /* Realtek GbE (00:e0:4c): the most common NIC vendor on consumer
     * Linux boxes; a bare-metal host draws less attention than a VM OUI. */
    .mac_oui = { 0x00, 0xe0, 0x4c },
};

/* ------------------------------------------------------------------ shell */

static const mp_telnet_behavior_t s_telnet = {
    .banner = "Linux 4.19",
    .login_prompt = "\r\nlinux login: ",
    .password_prompt = "Password: ",
    .login_failed = "Login incorrect",
    .shell_prompt = NULL, /* prompt is generated by the shell (user@host:cwd) */
    .max_retries = 3,
    .creds = s_creds,
    .n_creds = sizeof(s_creds) / sizeof(s_creds[0]),
    .cmds = NULL,
    .n_cmds = 0,
    .exec = NULL,
    .shell = mp_linuxsh_shell,
    .shell_ctx = &mp_linux419_shell_cfg,
};

/* OpenSSH 7.9p1: the upstream portable banner has no distro suffix. */
static const mp_ssh_behavior_t s_ssh = {
    .banner = "SSH-2.0-OpenSSH_7.9p1",
    .linger_ms = 4000,
};

/* Real SSH-2.0 transport (wolfSSH) carrying the 7.9p1 identity.
 * Non-const: key lengths are patched in brand init from the embedded
 * binary symbols (their difference is not a C constant expression). */
static mp_sshd_behavior_t s_sshd = {
    .banner = "SSH-2.0-OpenSSH_7.9p1",
    .creds = s_creds,
    .n_creds = sizeof(s_creds) / sizeof(s_creds[0]),
    .key_rsa = ssh_host_rsa_key_start,
    .key_ecdsa = ssh_host_ecdsa_key_start,
    .shell = mp_linuxsh_shell,
    .shell_ctx = &mp_linux419_shell_cfg,
};

/* vsftpd 3.0.3 over the same fake filesystem (read-only). */
static mp_ftpd_behavior_t s_ftpd = {
    .version = "3.0.3",
    .creds = s_creds,
    .n_creds = sizeof(s_creds) / sizeof(s_creds[0]),
    .fs = mp_linux419_fs,
    /* vsftpd's compiled-in defaults are 2000/50 (tunables.c), but a
     * honeypot wants the CVE-2021-30047 421 reachable: these must sit
     * below the global session budget (8) or the transport resets the
     * connection before any 421 can be sent. Low limits are also what
     * hardening guides recommend, so the config stays plausible. */
    .max_clients = 6,
    .max_per_ip = 4,
};

static const mp_brand_behavior_entry_t s_behaviors[] = {
    { "telnet",   &s_telnet   },
    { "http",     &s_http     },
    { "httpd",    &s_httpd    },
    { "ssh",      &s_ssh      },
    { "sshd",     &s_sshd     },
    { "ftpd",     &s_ftpd     },
    { NULL, NULL },
};

static esp_err_t linux419_init(const mp_brand_t *self)
{
    (void)self;
    s_sshd.key_rsa_len =
        (uint32_t)(ssh_host_rsa_key_end - ssh_host_rsa_key_start);
    s_sshd.key_ecdsa_len =
        (uint32_t)(ssh_host_ecdsa_key_end - ssh_host_ecdsa_key_start);
    s_ftpd.fs_n = mp_linux419_fs_n;
    /* runtime credential overrides (management plane); empty = defaults */
    mp_cfg_register(s_cred_keys, sizeof(s_cred_keys) / sizeof(s_cred_keys[0]));
    mp_linux419_shadow_rebuild();
    return ESP_OK;
}

const mp_brand_t mp_brand_linux419 = {
    .meta = &s_meta,
    .behaviors = s_behaviors,
    .init = linux419_init,
};
